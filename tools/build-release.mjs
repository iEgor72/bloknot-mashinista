import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const release = JSON.parse(fs.readFileSync(path.join(root, 'release.json')));
if (!/^\d+\.\d+\.\d+$/.test(release.version) || !/^v\d+$/.test(release.shell)) throw new Error('Invalid release metadata');
const check = process.argv.includes('--check');
let changed = [];
function write(name, value) {
  const file = path.join(root, name), before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (before === value) return;
  changed.push(name);
  if (!check) fs.writeFileSync(file, value);
}
const generated = '// Generated by tools/build-release.mjs from release.json.\nwindow.APP_RELEASE = Object.freeze(' + JSON.stringify(release) + ');\n';
write('scripts/release.js', generated);
const bootstrap = fs.readdirSync(root).filter(name => /^sw-bootstrap-v\d+\.js$/.test(name))
  .sort((a,b) => Number(a.match(/v(\d+)/)[1]) - Number(b.match(/v(\d+)/)[1])).at(-1);
write('sw-bootstrap-' + release.shell + '.js', fs.readFileSync(path.join(root, bootstrap), 'utf8')
  .replace(/(var version = ')v\d+(';)/, '$1' + release.shell + '$2'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json')));
pkg.version = release.version;
write('package.json', JSON.stringify(pkg, null, 2) + '\n');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json')));
lock.version = release.version; lock.packages[''].version = release.version;
write('package-lock.json', JSON.stringify(lock, null, 2) + '\n');
const files = ['index.html','sw.js', ...fs.readdirSync(path.join(root, 'scripts')).filter(x => /\.(?:js|mjs)$/.test(x)).map(x => 'scripts/' + x),
  ...fs.readdirSync(path.join(root, 'styles')).filter(x => x.endsWith('.css')).map(x => 'styles/' + x)];
for (const name of files) {
  let text = fs.readFileSync(path.join(root, name), 'utf8');
  // All versioned delivery paths and runtime module declarations share one release.
  text = text.replace(/(?<=\/(?:scripts|styles)\/)v\d+(?=\/)/g, release.shell)
    .replace(/sw-bootstrap-v\d+\.js/g, 'sw-bootstrap-' + release.shell + '.js')
    .replace(/(CACHE_VERSION\s*=\s*')v\d+(')/g, '$1' + release.shell + '$2')
    .replace(/(SHELL_CACHE_VERSION\s*=\s*')v\d+(')/g, '$1' + release.shell + '$2')
;
  if (name.endsWith('.js')) text = text.replace(/(registerShiftTrackerRuntimeModule\([^\n]*,\s*')v\d+('\))/g, '$1' + release.shell + '$2');
  if (name === 'scripts/app.js') text = text.replace(/var APP_VERSION = '[^']+';/, 'var APP_VERSION = window.APP_RELEASE.version;');
  write(name, text);
}
if (changed.length && check) { console.error('Stale release files:', changed.join(', ')); process.exit(1); }
for (const name of files.filter(x => /\.(?:js|mjs)$/.test(x)).concat(['server.js', 'scripts/journal/engine.mjs', 'scripts/journal/store.mjs', 'scripts/journal/merge.mjs'])) {
  const result = spawnSync(process.execPath, ['--check', path.join(root, name)], { encoding:'utf8' });
  if (result.status) throw new Error(name + ': ' + result.stderr);
}
console.log(`Release ${release.version} / ${release.shell}: ${check ? 'checked' : 'generated'} (${changed.length} updates)`);
